import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('../../modules/lensCalibration/RegionGeometry.js',import.meta.url),'utf8').replace(/^\.pragma library\s*/,'');
const api=vm.runInNewContext(source+';({color,nearest,contains,valid,snap})');
const polygon=[[0,0],[10,0],[10,10],[0,10]];
const hit=api.nearest(polygon,[-1,5],2);
assert.equal(hit.index,3);assert.deepEqual(Array.from(hit.point),[0,5]);
const next=polygon.map(p=>p.slice());next.splice(hit.index+1,0,hit.point);
assert.equal(next.length,5);assert.deepEqual(Array.from(next[4]),[0,5]);assert.equal(polygon.length,4);
assert.equal(api.contains(polygon,[5,5]),true);assert.equal(api.contains(polygon,[11,5]),false);
assert.equal(api.valid(polygon),true);assert.equal(api.valid([[0,0],[1,1],[2,2]]),false);assert.equal(api.valid([[0,0],[NaN,1],[2,0]]),false);
assert.equal(api.nearest(polygon,[50,50],1),null);
assert.equal(api.color('stable-id'),api.color('stable-id'));assert.match(api.color('stable-id'),/^#[0-9a-f]{6}$/);
const objects=[{vertices:[[2,2],[8,2]],edges:[[0,1]]}];
assert.deepEqual(Array.from(api.snap(objects,[2.1,2.1],1)),[2,2]);
assert.deepEqual(Array.from(api.snap(objects,[5,2.2],1)),[5,2]);
assert.deepEqual(Array.from(api.snap(objects,[5,7],1)),[5,7]);
console.log('Region geometry PASS: closing edge insertion, containment, validity, stable colors, projected vertex/edge snapping');

function normalizedCode(value, separator) {
    const parts = String(value || "").trim().replace(/-/g, "_").split("_");
    if (!parts[0]) return "";
    parts[0] = parts[0].toLowerCase();
    for (let index = 1; index < parts.length; index++) {
        parts[index] = parts[index].length === 4
            ? parts[index][0].toUpperCase() + parts[index].slice(1).toLowerCase()
            : parts[index].toUpperCase();
    }
    return parts.join(separator || "_");
}

function buildChoices(localeFactory, extraCodes, separator) {
    const rows = entries.slice();
    const seen = new Set(rows.map(row => normalizedCode(row.value, "_")));
    for (const candidate of extraCodes || []) {
        const value = normalizedCode(candidate, "_");
        if (!/^[a-z]{2,3}(?:_[A-Za-z]{2,4}){0,2}$/.test(value) || value === "auto" || seen.has(value)) continue;
        rows.push({value:value, language:value, territory:""});
        seen.add(value);
    }
    return rows.map(row => {
        const locale = localeFactory(row.value);
        const known = locale.name !== "C";
        const language = (known && locale.nativeLanguageName) || row.language;
        const territory = (known && (locale.nativeTerritoryName || locale.nativeCountryName)) || row.territory;
        const nativeName = territory ? language + " (" + territory + ")" : language;
        const englishName = row.territory ? row.language + " (" + row.territory + ")" : row.language;
        const code = normalizedCode(row.value, separator);
        return {
            value:code,
            name:nativeName + (nativeName.toLocaleLowerCase() === englishName.toLocaleLowerCase() ? "" : " · " + englishName) + " — " + code
        };
    }).sort((a, b) => a.name.localeCompare(b.name));
}
